"""Read only the reviewed PSI-26 as-run worksheet, with exact source identity.

Never read the planned workbook or export unrelated cells. Oxygen's percent
heading conflicts with fractional stored values, so it remains unscored raw data.
"""
from pathlib import Path
import ast, hashlib, json, math, sys, xml.etree.ElementTree as E, zipfile

SOURCE_SHA = '850910541fc9c802d00aa9de14758205103642184249b419c09868df2fbea6e8'
NS = {'s': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}

def extract(source):
    raw = Path(source).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA:
        raise ValueError('Reviewed PSI-26 workbook hash differs')
    with zipfile.ZipFile(source) as z:
        strings = [''.join(x.itertext()) for x in E.fromstring(z.read('xl/sharedStrings.xml')).findall('s:si', NS)]
        sheet = E.fromstring(z.read('xl/worksheets/sheet1.xml'))
        def value(c):
            v = c.find('s:v', NS)
            if v is None: return ''
            return strings[int(v.text)] if c.attrib.get('t') == 's' else v.text
        rows = []
        shared = {}
        def arithmetic(node):
            if isinstance(node, ast.Expression): return arithmetic(node.body)
            if isinstance(node, ast.Constant) and type(node.value) in (int, float): return node.value
            if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Div)):
                a, b = arithmetic(node.left), arithmetic(node.right)
                return a + b if isinstance(node.op, ast.Add) else a / b
            raise ValueError('Unreviewed pressure formula')
        for row in sheet.findall('.//s:row', NS):
            cells = {c.attrib['r'].rstrip('0123456789'): c for c in row}
            vals = {k: value(c) for k, c in cells.items() if k in ('C', 'D', 'E', 'F', 'K', 'AA', 'AB')}
            if not vals.get('C', '').isdigit(): continue
            c = cells.get('AB')
            if c is None or c.attrib.get('t') in ('s', 'e', 'b'):
                raise ValueError('Unexpected pressure cell type')
            pressure = float(vals['AB'])
            f = c.find('s:f', NS)
            formula = ''
            if f is not None:
                if f.text:
                    formula = f.text
                    if f.attrib.get('t') == 'shared': shared[f.attrib['si']] = formula
                else: formula = shared[f.attrib['si']]
                if not math.isclose(arithmetic(ast.parse(formula, mode='eval')), pressure, rel_tol=1e-12):
                    raise ValueError('Pressure formula cache differs from arithmetic')
            if not 0 < pressure < 2: raise ValueError('Unexpected atmosphere pressure')
            rows.append({'row': int(row.attrib['r']), 'run': vals['C'], 'test': vals.get('D', ''), 'sample': vals.get('E', ''), 'material': vals.get('F', ''), 'airDisplay': vals.get('K', ''), 'oxygenRaw': vals.get('AA', ''), 'pressureAtm': vals['AB'], 'pressureFormula': formula})
        if len(rows) != 121: raise ValueError('Reviewed row count differs')
        return rows

if __name__ == '__main__':
    rows = extract(sys.argv[1])
    output = Path(sys.argv[2])
    output.write_text('// Generated by scripts/extract-bass-asrun.py from the exact reviewed workbook.\nexport const BASS_ASRUN_DATA = ' + json.dumps(rows, ensure_ascii=True, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(json.dumps({'rows': len(rows), 'sourceSha256': SOURCE_SHA, 'output': str(output)}))
