import {readFile,writeFile,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export async function compileAgentSkills({check=false}={}){
 const directory=path.join(root,'lib/agent-skills'),skills=[];
 for(const name of (await readdir(directory)).sort()){
  const text=await readFile(path.join(directory,name,'SKILL.md'),'utf8');
  if(!text.startsWith('---\nname: '+name+'\n')||!text.includes('\ndescription: '))throw Error('Invalid agent skill: '+name);
  skills.push({id:name,version:['concise-dialogue','safety-checklist'].includes(name)?'0.5.1':'0.4.5',sha256:createHash('sha256').update(text).digest('hex'),instructions:text.slice(text.indexOf('\n---',4)+4).trim()});
 }
 const hash=createHash('sha256').update(JSON.stringify(skills)).digest('hex');
 const output='// Generated by scripts/compile-agent-skills.mjs. Do not edit.\nexport const AGENT_SKILL_HASH='+JSON.stringify(hash)+';\nexport const AGENT_SKILLS='+JSON.stringify(skills,null,2)+';\n';
 const target=path.join(root,'lib/agent-skill-manifest.mjs');
 if(check){if(await readFile(target,'utf8')!==output)throw Error('Agent skill manifest is stale. Run node scripts/compile-agent-skills.mjs.');}
 else await writeFile(target,output);
 return {count:skills.length,hash};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(await compileAgentSkills({check:process.argv.includes('--check')}));
